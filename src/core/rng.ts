/**
 * Deterministic PRNG. Both ends derive a drop's chunk selection from nothing but
 * the 32-bit seed carried in the packet, so sender and receiver must agree on
 * this exact sequence — never swap it for Math.random.
 */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
